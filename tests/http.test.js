"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs/promises");
const os = require("os");
const path = require("path");
const { hashPassword } = require("../src/password");

test("HTTP login, CSRF, portfolio recovery, contact honeypot and server rendering", async (t) => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "portfolio-http-"));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  Object.assign(process.env, { NODE_ENV: "development", DATA_DIR: dir, TRUST_PROXY: "0", SESSION_SECRET: "isolated-test-session-secret-123456789", ADMIN_USERNAME: "test-admin", ADMIN_PASSWORD_HASH: await hashPassword("Test-password-123!"), SESSION_COOKIE_NAME: "audit" });
  const app = require("../server");
  const server = app.listen(0, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = "http://127.0.0.1:" + server.address().port;
  let cookie = "";
  let csrf = "";
  const request = (route, method = "GET", body, useCsrf = true) => fetch(base + route, { method, headers: { Accept: "application/json", "Content-Type": "application/json", Cookie: "bad=%; " + cookie, ...(useCsrf ? { "x-csrf-token": csrf } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  assert.equal((await request("/api/admin/portfolio")).status, 401);
  const login = await request("/admin/login", "POST", { username: "test-admin", password: "Test-password-123!" });
  assert.equal(login.status, 200);
  cookie = login.headers.get("set-cookie").split(";")[0];
  csrf = (await (await request("/api/admin/session")).json()).csrfToken;
  assert.equal((await request("/api/admin/portfolio", "PUT", {}, false)).status, 403);
  assert.equal((await request("/api/admin/portfolio", "PUT", { projects: [null] })).status, 400);
  assert.equal((await request("/api/admin/portfolio", "PUT", { profile: { name: "HTTP Portfolio", heroSummary: "Visible without JavaScript" } })).status, 200);
  const html = await (await request("/")).text();
  assert.ok(html.includes("HTTP Portfolio"));
  assert.ok(html.includes("Visible without JavaScript"));
  assert.equal((await request("/assets/profile.svg")).status, 200);
  assert.equal((await request("/api/contact", "POST", { website: "spam" })).status, 202);
  assert.deepEqual(await (await request("/api/admin/messages")).json(), []);
  assert.equal((await request("/api/contact", "POST", { name: "Visitor", email: "visitor@example.com", message: "Hello" })).status, 202);
  const messages = await (await request("/api/admin/messages")).json();
  assert.equal(messages.length, 1);
  assert.equal((await request("/api/admin/messages/" + messages[0].id, "DELETE")).status, 200);
  assert.deepEqual(await (await request("/api/admin/messages")).json(), []);
});
